package ru.pacco.catalog.internal;

public enum ProductStatus {
    /** Ждёт модерации: карточка продавца прошла комплаенс, модератор ещё не проверил перевод и фото. */
    PENDING,
    /** В продаже. */
    PUBLISHED,
    /** Снят правилами комплаенса; вернётся в продажу, если правила это позволят. */
    BLOCKED,
    /** Отклонён модератором. */
    REJECTED
}
